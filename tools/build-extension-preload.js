"use strict";
// Builds scripts/extension-sw-preload.js from electron-chrome-extensions'
// preload: the same script, run only in an extension's own service worker.
// The library registers its preload for every service worker of a session,
// where it puts an "electron" object on the worker's global, so a site's
// own service worker would find it, and no Chrome has one. Run after
// updating electron-chrome-extensions: node tools/build-extension-preload.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(require.resolve("electron-chrome-extensions/preload", { paths: [root] }), "utf8");
const version = JSON.parse(fs.readFileSync(path.join(root, "node_modules", "electron-chrome-extensions", "package.json"), "utf8")).version;

const build = () => `// Generated by tools/build-extension-preload.js from electron-chrome-extensions ${version}
// (MIT, Samuel Maddock): its preload, run only in an extension's own service
// worker, never in a site's. Don't edit by hand.
"use strict";
(() => {
  let url = "";
  try {
    url = String(require("electron").contextBridge.executeInMainWorld({ func: () => self.location.href }));
  } catch (error) {
    return;
  }
  if (!url.startsWith("chrome-extension://")) {
    return;
  }
${source}
})();
`;

// Electron runs no preload in an extension's service worker (only in a
// site's), so the worker is given the same code in front of its own
// script (see main/extension-bridge.js), with what the preload would have
// had from Electron made here: its calls and events go to the app over
// fetch, to the app's own address on this computer (put in place of
// __NOOR_BRIDGE_ENDPOINT__ as the worker is given the code), instead of
// Electron's IPC.
// The library's build logs every call it carries; the worker's console
// is left to the extension.
const quiet = (code) => code.replace(/if \(true\) \{(\s*console\.log\()/g, "if (false) {$1");

const buildBridge = () => `// Generated by tools/build-extension-preload.js from electron-chrome-extensions ${version}
// (MIT, Samuel Maddock): its preload, run in front of an extension's service
// worker (see main/extension-bridge.js), its calls and events carried over
// fetch instead of Electron's IPC. Don't edit by hand.
"use strict";
(() => {
  if (typeof self === "undefined" || !String(self.location && self.location.href).startsWith("chrome-extension://")) {
    return;
  }
  // The library's API already here (from a preload): nothing to add.
  if (self.chrome && self.chrome.windows && typeof self.chrome.windows.getLastFocused === "function") {
    return;
  }
  const ENDPOINT = "__NOOR_BRIDGE_ENDPOINT__";
  const post = (what, body) => fetch(ENDPOINT + what, { method: "POST", cache: "no-store", body: JSON.stringify(body || {}) })
    .then((response) => response.json().then((data) => {
      if (!response.ok) {
        throw new Error((data && data.error) || "The app didn't answer");
      }
      return data;
    }));
  const handlers = new Map();
  // Events wait in the app until the worker asks for them, once it listens to any.
  let polling = false;
  const poll = () => {
    if (polling) {
      return;
    }
    polling = true;
    const next = () => post("events").then((events) => {
      for (const [name, args] of events) {
        for (const handler of [...(handlers.get("crx-" + name) || [])]) {
          try {
            handler({}, ...args);
          } catch (error) {
            console.error(error);
          }
        }
      }
    }).catch(() => new Promise((resolve) => setTimeout(resolve, 1000))).then(next);
    next();
  };
  const ipcRenderer = {
    invoke: (channel, extensionId, name, ...args) => (channel === "crx-msg"
      ? post("invoke", { name, args }).then((data) => (data.none ? undefined : data.result))
      : Promise.reject(new Error(channel + " isn't available in a service worker"))),
    send: (channel, extensionId, name) => {
      if (channel === "crx-add-listener") {
        post("listen", { name }).catch(() => {});
        poll();
      } else if (channel === "crx-remove-listener") {
        post("unlisten", { name }).catch(() => {});
      }
    },
    addListener: (channel, handler) => {
      if (!handlers.has(channel)) {
        handlers.set(channel, new Set());
      }
      handlers.get(channel).add(handler);
      return ipcRenderer;
    },
    removeListener: (channel, handler) => {
      const set = handlers.get(channel);
      if (set) {
        set.delete(handler);
      }
      return ipcRenderer;
    },
  };
  ipcRenderer.on = ipcRenderer.addListener;
  const electron = {
    ipcRenderer,
    contextBridge: {
      exposeInMainWorld: (key, value) => { self[key] = value; },
      executeInMainWorld: ({ func, args }) => func(...(args || [])),
    },
    webFrame: { executeJavaScript: () => Promise.resolve() },
  };
  const require = (name) => {
    if (name === "electron") {
      return electron;
    }
    throw new Error("Cannot find module '" + name + "'");
  };
  const process = { type: "service-worker", contextIsolated: true };
${quiet(source)}
})();
`;

module.exports = { build, buildBridge };

if (require.main === module) {
  const out = path.join(root, "scripts", "extension-sw-preload.js");
  fs.writeFileSync(out, build());
  console.log(`wrote ${out}`);
  const bridge = path.join(root, "scripts", "extension-sw-bridge.js");
  fs.writeFileSync(bridge, buildBridge());
  console.log(`wrote ${bridge}`);
}
