// Builds scripts/parts/android-surface.js: what this app's Chromium shows a
// page that Chrome on Android, of the same version, doesn't have (Web HID,
// the screen pickers, desktop picture-in-picture…), so Noor Android can take
// it away (see scripts/parts/android.js).
//
// Usage: node tools/android_surface.js <surface.json> <browser-compat-data/data.json>
//
// The same two files as tools/iphone_surface.js reads: what
// tools/dump-surface.js lists, run with the app's Electron, and MDN's
// browser compatibility data (npm package @mdn/browser-compat-data), which
// says, for each feature, from which Chrome on Android version it is there.
// Rerun both when Electron is updated.
"use strict";
const fs = require("fs");
const path = require("path");

const surface = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const bcd = JSON.parse(fs.readFileSync(process.argv[3], "utf8"));
const out = path.join(__dirname, "..", "scripts", "parts", "android-surface.js");
const MAJOR = Number(String(surface.chrome).split(".")[0]);

/// Whether Chrome on Android of this version has a feature, as BCD says:
/// true, false (never, or not yet, or no more), or null when BCD doesn't say.
const onAndroid = (node) => {
  const support = node && node.__compat && node.__compat.support && node.__compat.support.chrome_android;
  if (!support) return null;
  let known = false;
  for (const statement of [].concat(support)) {
    if (statement.flags || statement.prefix || statement.alternative_name) continue;
    const added = statement.version_added;
    if (added === false) {
      known = true;
      continue;
    }
    if (added === null || added === undefined || added === "preview") continue;
    known = true;
    const from = added === true ? 1 : Number(String(added).replace("≤", ""));
    const until = statement.version_removed ? Number(String(statement.version_removed).replace("≤", "")) : Infinity;
    if (from <= MAJOR && MAJOR < until) return true;
  }
  return known ? false : null;
};

/// Kept whatever BCD says (the shapes of every interface).
const KEEP = new Set(["constructor", "prototype", "length", "name", "arguments", "caller"]);

const api = bcd.api;
const builtins = bcd.javascript.builtins;
const table = {};
const put = (where, name, has) => {
  if (has !== false || KEEP.has(name)) return;
  const list = (table[where] = table[where] || []);
  if (!list.includes(name)) list.push(name);
};

for (const scope of ["window", "worker"]) {
  const dump = surface[scope];
  for (const name of dump.globals || []) {
    if (/^on/.test(name)) continue;
    let has = null;
    if (api[name]) has = onAndroid(api[name]);
    else if (builtins[name]) has = onAndroid(builtins[name]);
    else {
      const owner = scope === "worker" ? api.WorkerGlobalScope : api.Window;
      if (owner && owner[name]) has = onAndroid(owner[name]);
    }
    put(scope, name, has);
  }
  for (const [name, own] of Object.entries(dump.interfaces || {})) {
    const node = api[name];
    if (!node) continue;
    const at = (member) => (/^on/.test(member) ? null : onAndroid(node[member]));
    for (const member of own.own || []) put(name, member, at(`${member}_static`) !== null ? at(`${member}_static`) : at(member));
    for (const member of own.prototype || []) put(`${name}.prototype`, member, at(member));
  }
}

const sorted = Object.fromEntries(Object.keys(table).sort().map((where) => [where, table[where].sort()]));
const body = JSON.stringify(sorted, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}");
const source = `// Generated by tools/android_surface.js from Chromium ${surface.chrome} and MDN's
// browser compatibility data. Don't edit by hand; rerun the tool.
//
// What a page sees in this app's Chromium and Chrome on Android of the same
// version lacks, by where it is (the window's globals, a worker's, an
// interface's own properties or its prototype's). See
// scripts/parts/android.js.
const ANDROID_SURFACE = ${body};
`;
fs.writeFileSync(out, source);
const count = Object.values(sorted).reduce((n, names) => n + names.length, 0);
console.log(`wrote ${out}: ${count} names in ${Object.keys(sorted).length} places for Chrome ${MAJOR}, ${source.length} chars`);
